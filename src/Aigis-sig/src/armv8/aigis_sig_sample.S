/* Decode the initial Eta1 buffer in 32-candidate batches.  Compact values are
 * kept as 16-bit lanes in a bounded stack scratch and expanded on copy-out. */
    .p2align 4
    .global PQCP_AIGIS_SIG_RejectEta1InitialArmv8
    .hidden PQCP_AIGIS_SIG_RejectEta1InitialArmv8
    .type PQCP_AIGIS_SIG_RejectEta1InitialArmv8, %function
PQCP_AIGIS_SIG_RejectEta1InitialArmv8:
    sub sp, sp, #1088
    mov x3, sp
    mov w4, #0
    adr x5, .Leta8_compact_table
    adr x6, .Leta8_compact_counts
    adr x7, .Leta8_weights
    ldr q31, [x7]
    adr x7, .Leta1_extract_tables
    ldp q22, q23, [x7]
    ldr q26, [x7, #32]
    movi v27.16b, #3
    movi v30.8h, #3

.macro reject_eta1_compact value
    cmhi v4.8h, v30.8h, v\value\().8h
    and v4.16b, v4.16b, v31.16b
    uaddlv s20, v4.8h
    fmov w7, s20
    add x9, x5, w7, uxtw #4
    ldr q24, [x9]
    tbl v\value\().16b, {v\value\().16b}, v24.16b
    ldrb w7, [x6, w7, uxtw]
    str q\value, [x3]
    add x3, x3, w7, uxtw #1
    add w4, w4, w7
.endm

.Lreject_eta1_initial_loop:
    cmp w4, #512
    b.hs .Lreject_eta1_initial_copy
    cmp w2, #8
    b.lo .Lreject_eta1_initial_copy
    sub w2, w2, #8
    movi v0.16b, #0
    ldr d0, [x1], #8
    tbl v20.16b, {v0.16b}, v22.16b
    tbl v21.16b, {v0.16b}, v23.16b
    ushl v20.16b, v20.16b, v26.16b
    ushl v21.16b, v21.16b, v26.16b
    and v20.16b, v20.16b, v27.16b
    and v21.16b, v21.16b, v27.16b
    uxtl v16.8h, v20.8b
    uxtl2 v17.8h, v20.16b
    uxtl v18.8h, v21.8b
    uxtl2 v19.8h, v21.16b
    reject_eta1_compact 16
    reject_eta1_compact 17
    reject_eta1_compact 18
    reject_eta1_compact 19
    b .Lreject_eta1_initial_loop

.Lreject_eta1_initial_copy:
    cmp w4, #512
    mov w7, #512
    csel w4, w4, w7, lo
    mov x1, sp
    mov w2, w4
    movi v7.8h, #1
.Lreject_eta1_copy16:
    cmp w2, #16
    b.lo .Lreject_eta1_copy_tail
    ldp q16, q18, [x1], #32
    sub v16.8h, v7.8h, v16.8h
    sub v18.8h, v7.8h, v18.8h
    sxtl v20.4s, v16.4h
    sxtl2 v21.4s, v16.8h
    sxtl v22.4s, v18.4h
    sxtl2 v23.4s, v18.8h
    stp q20, q21, [x0], #32
    stp q22, q23, [x0], #32
    sub w2, w2, #16
    b .Lreject_eta1_copy16
.Lreject_eta1_copy_tail:
    cbz w2, .Lreject_eta1_initial_done
    mov w7, #1
.Lreject_eta1_copy_tail_loop:
    ldrh w8, [x1], #2
    sub w8, w7, w8
    str w8, [x0], #4
    subs w2, w2, #1
    b.ne .Lreject_eta1_copy_tail_loop
.Lreject_eta1_initial_done:
    mov x1, sp
    movi v0.16b, #0
    mov w2, #68
.Lreject_eta1_clean_stack:
    str q0, [x1], #16
    subs w2, w2, #1
    b.ne .Lreject_eta1_clean_stack
    mov w0, w4
    add sp, sp, #1088
    ret
    .size PQCP_AIGIS_SIG_RejectEta1InitialArmv8, .-PQCP_AIGIS_SIG_RejectEta1InitialArmv8
    .purgem reject_eta1_compact

