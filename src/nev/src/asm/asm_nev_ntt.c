// Reference poly_ntt: apply the per-block transform to each of the n / nttDim
// contiguous blocks of nttDim coefficients.
void NEV_PolyNtt(NEV_Poly *r, const CRYPT_NevInfo *info)
{
    uint32_t dim = info->nttDim;
    uint32_t n = info->n;
    uint32_t i;
#ifdef HITLS_CRYPTO_NEV_SVE2
    if (NEV_Sve2Enabled() != 0) {
        if (info->q == 769) {
            NEV_POLY_NTT128_Q769_SVE2(r->coeffs, NEV_NTT_SVE2_TABLE_769, n);
        } else if (info->q == 1409) {
            NEV_POLY_NTT64_Q1409_SVE2(r->coeffs, NEV_NTT_SVE2_TABLE_1409, n);
        } else {
            NEV_POLY_NTT128_Q3329_SVE2(r->coeffs, NEV_NTT_SVE2_TABLE_3329, n);
        }
        return;
    }
#endif
    if (info->q == 769) {
        for (i = 0; i < n; i += dim) {
            NEV_NTT128_Q769(&r->coeffs[i], NEV_NTT_TABLE_769);
        }
    } else if (info->q == 1409) {
        for (i = 0; i < n; i += dim) {
            NEV_NTT64_Q1409(&r->coeffs[i], NEV_NTT_TABLE_1409);
        }
    } else {
        for (i = 0; i < n; i += dim) {
            NEV_NTT128_Q3329(&r->coeffs[i], NEV_NTT_TABLE_3329);
        }
    }
}

