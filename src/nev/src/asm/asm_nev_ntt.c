/*
 * ARMv8 NEON backend for NEV_PolyNtt / NEV_PolyInvNtt (replaces nev_ntt.c at
 * link time).  The per-q, per-direction assembly kernels in
 * asm/nev_ntt_armv8.S transform one nttDim-sized block in place under the v2
 * congruence contract (see the assembly header): the forward output is
 * bit-identical to the generic C backend (both end with the proven exact
 * Barrett pass); the inverse output is congruent mod q with |x| <= 0.91*q,
 * which the downstream unique canonicalizers map to identical bytes.
 *
 * Twiddle table layout (int16 units; every twiddle is the lane-interleaved
 * Barrett pair (root, root_hi) consumed by the kernels' 3-instruction
 * mul/sqrdmulh/mls multiply — the ML-KEM convention of asm_ml_kem_ntt.c:
 * root is the centered PLAIN twiddle mod+-(z_mont * 2^-16 mod q), i.e. the
 * value the Plantard tables of nev_ntt.c encode, and
 * root_hi = round_even(root * 2^16 / q) / 2):
 *
 * Forward (dim 128; dim 64 in brackets where different):
 *   [0..1]   padding — the kernel overwrites these lanes with q and barrettV
 *   [2..31]  zeta_1..zeta_15 pairs for the whole-register layers
 *            len 64,32,16,8   [dim 64: [2..15] zeta_1..zeta_7 for len 32,16,8]
 *   then 4 [2] groups of 80, one per aligned run of 4 data registers
 *   (original vector indices i = 4g..4g+3), each 10 vectors of 8 lanes:
 *     Z4lo,Z4hi   len=4 twiddles  zeta_{o4+i}, each lane-doubled
 *     ZAlo,ZAhi   len=2 twiddles  zeta_{o2+2i}, lane-doubled
 *     ZBlo,ZBhi   len=2 twiddles  zeta_{o2+2i+1}, lane-doubled
 *     ZClo,ZChi   len=1 twiddles  zeta_{o1+4i}, zeta_{o1+4i+1} interleaved
 *     ZDlo,ZDhi   len=1 twiddles  zeta_{o1+4i+2}, zeta_{o1+4i+3} interleaved
 *   with (o4, o2, o1) = (16, 32, 64) [dim 64: (8, 16, 32)].
 *
 * Inverse (the C inverse walks the forward zeta table backwards):
 *   [0..1]   padding (q / barrettV lanes)
 *   [2..31]  zeta_15..zeta_1 pairs, in Gentleman-Sande consumption order for
 *            len 8,16,32   [dim 64: [2..15] zeta_7..zeta_1 for len 8,16]
 *            (the zeta_1 pair is retained for layout symmetry but unused:
 *            the last GS layer is fused with the mont^2/dim scale, whose
 *            (fP, fP_hi, fzetaP, fzetaP_hi) pairs are movz/movk immediates
 *            in the kernels — no table tail slot)
 *   then 4 [2] groups of 80:
 *     ZClo,ZChi   len=1  zeta_{D-1-4i}, zeta_{D-2-4i} interleaved (D = nttDim)
 *     ZDlo,ZDhi   len=1  zeta_{D-3-4i}, zeta_{D-4-4i} interleaved
 *     ZAlo,ZAhi   len=2  zeta_{D/2-1-2i}, lane-doubled
 *     ZBlo,ZBhi   len=2  zeta_{D/2-2-2i}, lane-doubled
 *     Z4lo,Z4hi   len=4  zeta_{D/4-1-i}, lane-doubled
 *
 * Generation script (verified against these tables; the script also proves,
 * by exhaustive sweep over all 65536 int16 inputs a for every distinct table
 * entry and fused constant, that the kernels' mul/sqrdmulh/mls multiply
 * satisfies  mm3(a) == a*root - hi*q exactly (the mls never wraps),
 * mm3(a) === a * root === NEV_FqMul(z_mont, a) (mod q),
 * |mm3(a)| <= q/2 + q*|a|/2^16, and mm3(a) - NEV_FqMul(z_mont, a) is in
 * {-q, 0, +q} with non-zero deviation only at sqrdmulh rounding ties; and
 * that the sqdmulh/srshr/mls Barrett matches NEV_BarrettReduce bit-for-bit
 * and returns the unique centered representative):
 *
 *   import numpy as np
 *   from fractions import Fraction
 *   A = np.arange(-32768, 32768, dtype=np.int64)
 *   def s16(x): return ((x & 0xFFFF) ^ 0x8000) - 0x8000
 *   def mod_pm(a, q):
 *       r = a % q
 *       return r - q if r > q // 2 else r
 *
 *   # ZP[q] = NEV_ZETAS_PLANTARD_<q> from nev_ntt.c (int32 Plantard tables);
 *   # FP[q]/FZ[q] = NEV_INTT_F_PLANTARD_<q> / NEV_INTT_FZETA_PLANTARD_<q>;
 *   # PARAMS from the table in nev.c: q: (qinv, barrettV, barrettShift, dim)
 *   PARAMS = {769: (64769, 21817, 24, 128), 1409: (14977, 23814, 25, 64),
 *             3329: (62209, 20159, 26, 128)}
 *
 *   def from_plantard(x, q):       # invert nev_ntt.c to_plantard()
 *       r = (x * q) % (1 << 32)
 *       return mod_pm(-r * pow(1 << 32, -1, q) % q, q)
 *
 *   def barrett_hi(v, q):          # ML-KEM convention (asm_ml_kem_ntt.c)
 *       t = Fraction(v * (1 << 16), q)
 *       r = round(t)
 *       if r % 2 != 0: r = r + 1 if r <= t else r - 1  # round-to-even
 *       return r // 2
 *
 *   def montref(zm, q, qinv):      # C NEV_FqMul(z_mont, a), all a
 *       prod = zm * A
 *       t = s16(s16(prod) * s16(qinv))
 *       return (prod - t * q) >> 16
 *
 *   def pair(root, q):             # (root, root_hi), exhaustively verified
 *       qinv, v, s, dim = PARAMS[q]
 *       hi = barrett_hi(root, q)
 *       lo = s16(A * root)
 *       h = (2 * A * hi + (1 << 15)) >> 16          # sqrdmulh
 *       res = s16((lo - s16(h * q)) & 0xFFFF)       # mls
 *       assert (res == A * root - h * q).all()
 *       assert ((res - A * root) % q == 0).all()
 *       assert (np.abs(res) <= q / 2 + q * np.abs(A) / 65536.0).all()
 *       d = res - montref(mod_pm(root * (1 << 16), q), q, qinv)
 *       assert set(np.unique(d)) <= {-q, 0, q}
 *       return root, hi
 *
 *   def interleave(ps):            # 8 pairs -> 8 root lanes, 8 hi lanes
 *       return [p[0] for p in ps] + [p[1] for p in ps]
 *
 *   def fwd_table(q):
 *       qinv, v, s, dim = PARAMS[q]
 *       Z = [from_plantard(x, q) for x in ZP[q]]
 *       z = lambda k: pair(Z[k], q)
 *       T = [0, 0]
 *       for k in range(1, dim // 8): T += list(z(k))
 *       for g in range(dim // 32):
 *           i4 = [4 * g + j for j in range(4)]
 *           o4, o2, o1 = dim // 8, dim // 4, dim // 2
 *           for vec in ([z(o4 + i) for i in i4 for _ in (0, 1)],
 *                       [z(o2 + 2 * i) for i in i4 for _ in (0, 1)],
 *                       [z(o2 + 2 * i + 1) for i in i4 for _ in (0, 1)],
 *                       [z(o1 + 4 * i + k) for i in i4 for k in (0, 1)],
 *                       [z(o1 + 4 * i + k) for i in i4 for k in (2, 3)]):
 *               T += interleave(vec)
 *       return T
 *
 *   def inv_table(q):
 *       qinv, v, s, dim = PARAMS[q]
 *       Z = [from_plantard(x, q) for x in ZP[q]]
 *       z = lambda k: pair(Z[k], q)
 *       T = [0, 0]
 *       for k in range(dim // 8 - 1, 0, -1): T += list(z(k))
 *       for g in range(dim // 32):
 *           i4 = [4 * g + j for j in range(4)]
 *           for vec in ([z(dim - 1 - 4 * i - k) for i in i4 for k in (0, 1)],
 *                       [z(dim - 3 - 4 * i - k) for i in i4 for k in (0, 1)],
 *                       [z(dim // 2 - 1 - 2 * i) for i in i4 for _ in (0, 1)],
 *                       [z(dim // 2 - 2 - 2 * i) for i in i4 for _ in (0, 1)],
 *                       [z(dim // 4 - 1 - i) for i in i4 for _ in (0, 1)]):
 *               T += interleave(vec)
 *       return T                   # no tail: fused scale pairs are immediates
 *
 *   def fused_consts(q):           # kernel movz/movk immediates
 *       qinv, v, s, dim = PARAMS[q]
 *       Z = [from_plantard(x, q) for x in ZP[q]]
 *       fp = from_plantard(FP[q], q)
 *       fz = from_plantard(FZ[q], q)
 *       assert fp == mod_pm((1 << 16) // dim, q)
 *       assert fz == mod_pm(fp * Z[1], q)
 *       return pair(fp, q), pair(fz, q)
 *
 *   def check_barrett(q):          # asm sqdmulh/srshr/mls == C, centered
 *       qinv, v, s, dim = PARAMS[q]
 *       t = s16((v * A + (1 << (s - 1))) >> s)
 *       tv = (((2 * A * v) >> 16) + (1 << (s - 16))) >> (s - 15)
 *       assert (s16(A - t * q) == s16(A - tv * q)).all()
 *       assert (np.abs(s16(A - t * q)) <= (q - 1) // 2).all()
 *
 * Fused-scale immediates produced by fused_consts (also listed in the .S):
 *   q=769:  fP = (-257, -10951), fzetaP = (215, 9161)
 *   q=1409: fP = (-385, -8954),  fzetaP = (696, 16186)
 *   q=3329: fP = (512, 5040),    fzetaP = (-266, -2618)
 */

